#!/usr/bin/env bash
# Regenerates src/nativeTest/kotlin/kron/glyph11/Corpus.kt, the golden outcomes the native tests hold the port to:
# Ktron's glyph11 corpus (src/test/resources/vectors) through Ktron's reference - UltraHardenedParser and
# BodyFramingDetector for a request head parsed whole, the ChunkedBodyStream loop for a chunked body.
#
#   JAVA_HOME=<a JDK 25> glyph11/golden-corpus.sh [a Ktron checkout, by default the one next to this repo]
#
# The generator below runs as a test inside Ktron's glyph11 and is deleted after: Ktron is left as it was.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
ktron=$(cd "${1:-$here/../../Ktron}" && pwd)
gen=$ktron/glyph11/src/test/kotlin/GoldenCorpus.kt
[ ! -e "$gen" ] || { echo "$gen exists already" >&2; exit 1; }
trap 'rm -f "$gen"' EXIT

cat > "$gen" <<'KOTLIN'
package ktron.glyph11

import ktron.glyph11.parser.ParserLimits
import java.io.File
import kotlin.test.Test

class GoldenCorpus {
    // a Kotlin string literal, one char per byte
    private fun q(s: String): String = buildString {
        append('"')
        for (c in s) when (c) {
            '\\', '"', '$' -> append('\\').append(c)
            '\r' -> append("\\r")
            '\n' -> append("\\n")
            '\t' -> append("\\t")
            in ' '..'~' -> append(c)
            else -> append("\\u%04x".format(c.code))
        }
        append('"')
    }

    private fun q(b: ByteArray) = q(String(b, Charsets.ISO_8859_1))

    private fun pairs(l: List<Pair<String, String>>) = l.joinToString(", ", "listOf(", ")") { "${q(it.first)} to ${q(it.second)}" }

    private fun limits(l: ParserLimits) =
        Vectors.describe(l).let { if (it == "-") "ParserLimits.Default" else "ParserLimits(${it.replace("=", " = ").replace(",", ", ")})" }

    private fun outcome(o: Outcome) = when (o.kind) {
        Outcome.ACCEPTED -> "Outcome.accepted(${o.headLength}, ${q(o.method)}, ${q(o.path)}, ${q(o.query)}, ${q(o.version)}, " +
            "${pairs(o.headers)}, ${pairs(o.params)}, ${o.framing}, ${o.contentLength}L)"
        Outcome.REFUSED -> "Outcome.refused(${o.status}, ${q(o.message!!)})"
        Outcome.INCOMPLETE -> "Outcome.incomplete"
        else -> error("not a golden outcome: $o")
    }

    private fun outcome(o: ChunkOutcome) = when (o.kind) {
        Outcome.ACCEPTED -> "ChunkOutcome.decoded(${o.wire}, ${q(o.payload)})"
        Outcome.REFUSED -> "ChunkOutcome.refused(${o.status}, ${q(o.message!!)})"
        Outcome.INCOMPLETE -> "ChunkOutcome.incomplete"
        else -> error("not a golden outcome: $o")
    }

    @Test
    fun generate() {
        val out = File(System.getenv("GLYPH11_CORPUS") ?: return)
        out.writeText(buildString {
            append("// Generated by glyph11/golden-corpus.sh from Ktron ${System.getenv("GLYPH11_CORPUS_FROM")}: every vector of its ")
            append("glyph11 corpus, with the outcome\n// Ktron's reference gives it whole. Do not edit.\n")
            append("package kron.glyph11\n\ninternal object Corpus {\n    val requests: List<CorpusRequest> = listOf(\n")
            for (v in Vectors.requests) {
                val o = Outcomes.reference(v.bytes, 0, v.bytes.size, v.limits)
                append("        CorpusRequest(${q(v.source)}, ${limits(v.limits)}, ${q(v.bytes)}, ${outcome(o)}),\n")
            }
            append("    )\n\n    val chunked: List<CorpusBody> = listOf(\n")
            for (b in Vectors.chunked) append("        CorpusBody(${q(b)}, ${outcome(Outcomes.referenceChunked(b, 0, b.size))}),\n")
            append("    )\n}\n")
        })
    }
}
KOTLIN

cd "$ktron"
GLYPH11_CORPUS="$here/src/nativeTest/kotlin/kron/glyph11/Corpus.kt" GLYPH11_CORPUS_FROM="$(git rev-parse --short HEAD)" \
    ./gradlew --no-daemon --quiet :glyph11:test --rerun --tests ktron.glyph11.GoldenCorpus
